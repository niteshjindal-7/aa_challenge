-- Ground Truth Query: Pull 1000 members with validated ancillary test results
-- Source: Snowflake MARTS_PREVIOUS.DPS
-- Date range: 2026 Q1 (Jan-Mar)
-- Filters: valid results only (HASINVALIDRESULT = FALSE), non-null lab results

WITH result_map (DIMRESULTSGROUPHASHKEY, RESULT_TYPE, MIN_VAL, MAX_VAL) AS (
    SELECT * FROM VALUES
        ('46da65fd76a8e70b0c71c3c5ccc4d3bc', 'SPIRO_FEV1_FVC_RATIO',     0.20, 1.00),
        ('dcb3a22c5fc3b265602bed938755018a', 'SPIRO_FEV1_PCT_PRED(?)',   10,   200),
        ('809f280d35b1fd6694dabd0f49706dd2', 'SPIRO_FVC_PCT_PRED(?)',    10,   200),
        ('416bec648a5f259c1b2d1fd131194d5d', 'SPIRO_SESSION_GRADE',      NULL, NULL),
        ('77e6d7fcd2f4f027bda30afb29338593', 'HBA1C_PCT',                3,    20),
        ('5e89f9ceb03203dc5b2bd184ddf7a7d5', 'UACR_MG_G',                0.01, 5000),
        ('7c55b73fa5540a5a6c3040793cb58139', 'COG_SCORE',                1,    99),
        ('7f73e6dac6ea0c30ffd2fda9562f1dc4', 'FOBT_RESULT',              NULL, NULL)
),
base AS (
    SELECT
        a.MEMBERPLANID,
        a.EVALUATIONID,
        a.DATEOFSERVICE,
        UPPER(COALESCE(NULLIF(TRIM(r.PRODUCTCODE), ''), NULLIF(TRIM(a.PRODUCTCODE), ''))) AS PRODUCTCODE,
        r.SIDE,
        r.DIMRESULTSGROUPHASHKEY,
        TRIM(r.LAB_RESULTS)                AS LAB_RESULTS,
        TRY_TO_DOUBLE(TRIM(r.LAB_RESULTS)) AS LAB_VALUE_NUM,
        s.SEVERITYGROUPCODE
    FROM MARTS_PREVIOUS.DPS.FACTANCILLARY a
    JOIN MARTS_PREVIOUS.DPS.FACTANCILLARYRESULTS r
        ON a.FACTANCILLARYHASHKEY = r.FACTANCILLARYHASHKEY
    LEFT JOIN MARTS_PREVIOUS.DPS.DIMSEVERITYGROUP s
        ON r.DIMSEVERITYGROUPHASHKEY = s.DIMSEVERITYGROUPHASHKEY
    WHERE a.YEAR = 2026
      AND a.DATEOFSERVICE BETWEEN '2026-01-01' AND '2026-03-31'
      AND a.EVALUATIONID IS NOT NULL
      AND a.MEMBERPLANID IS NOT NULL
      AND NULLIF(TRIM(r.LAB_RESULTS), '') IS NOT NULL
      AND COALESCE(NULLIF(TRIM(r.PRODUCTCODE), ''), NULLIF(TRIM(a.PRODUCTCODE), '')) IS NOT NULL
      AND COALESCE(r.HASINVALIDRESULT, FALSE) = FALSE
),
clean AS (
    SELECT b.*, m.RESULT_TYPE
    FROM base b
    JOIN result_map m
        ON b.DIMRESULTSGROUPHASHKEY = m.DIMRESULTSGROUPHASHKEY
    WHERE CASE
        WHEN m.RESULT_TYPE = 'FOBT_RESULT'         THEN UPPER(b.LAB_RESULTS) IN ('POSITIVE', 'NEGATIVE')
        WHEN m.RESULT_TYPE = 'SPIRO_SESSION_GRADE' THEN UPPER(b.LAB_RESULTS) IN ('A','B','C','D','E','F','U')
        ELSE b.LAB_VALUE_NUM BETWEEN m.MIN_VAL AND m.MAX_VAL
    END

    UNION ALL

    SELECT b.*, 'CECG_FINDING' AS RESULT_TYPE
    FROM base b
    WHERE b.PRODUCTCODE = 'CECG'
      AND b.SEVERITYGROUPCODE IS NOT NULL
),
members AS (
    SELECT DISTINCT MEMBERPLANID
    FROM clean
    ORDER BY MEMBERPLANID
    LIMIT 1000
)
SELECT
    c.MEMBERPLANID,
    c.EVALUATIONID,
    c.DATEOFSERVICE,
    c.PRODUCTCODE,
    c.RESULT_TYPE,
    c.SIDE,
    c.LAB_RESULTS,
    c.LAB_VALUE_NUM,
    c.SEVERITYGROUPCODE,
    IFF(c.RESULT_TYPE = 'UACR_MG_G' AND c.LAB_VALUE_NUM = 29.999, TRUE, FALSE) AS IS_UACR_BELOW_30
FROM clean c
JOIN members m
    ON c.MEMBERPLANID = m.MEMBERPLANID
ORDER BY c.MEMBERPLANID, c.DATEOFSERVICE, c.PRODUCTCODE, c.RESULT_TYPE, c.SIDE;
